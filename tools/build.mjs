// Bundles dev.html + css/ + js/ + three.js into a single self-contained index.html
// that opens straight from disk (double-click) or any static host.
// Usage: npm run build
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const at = (p) => root + p;

const result = await build({
  entryPoints: [at('js/main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2020',
  write: false,
  alias: { three: at('vendor/three.module.min.js') },
  legalComments: 'none',
  logLevel: 'warning',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = (await readFile(at('css/style.css'), 'utf8')).replace(/<\/style/gi, '<\\/style');
let html = await readFile(at('dev.html'), 'utf8');

const swap = (from, to) => {
  if (!html.includes(from)) throw new Error(`dev.html is missing: ${from}`);
  html = html.replace(from, () => to);
};
swap('<link rel="stylesheet" href="css/style.css">', `<style>\n${css}</style>`);
swap(/<script type="importmap">.*?<\/script>\n/.exec(html)[0], '');
swap('<script type="module" src="js/main.js"></script>', `<script>\n${js}</script>`);
swap('<html lang="en">', '<html lang="en">\n<!-- Generated by `npm run build` from dev.html, css/ and js/. Edit those, not this file. -->');

await writeFile(at('index.html'), html);
console.log(`index.html written (${(html.length / 1024).toFixed(0)} KB)`);
